    /// <summary>One documented case where an option's chosen shape is not a fixed point of a tool.</summary>
    private sealed record Divergence(string Key, string Tool, string Reason, string ExampleCase);

    /// <summary>
    /// Reads build/conformance-divergences.json — the same file <c>verifyExpectations</c> and
    /// <c>verifyExpectationsJb</c> check a discovered non-fixed-point against — and groups its entries by
    /// option key, so each generated page can say what it says for itself rather than pointing at a
    /// registry the reader has to go cross-reference by hand.
    /// </summary>
    private static ILookup<string, Divergence> LoadDivergences(string root)
    {
        var path = Path.Combine(root, "build", "conformance-divergences.json");
        using var doc = JsonDocument.Parse(File.ReadAllText(path));
        return doc.RootElement.GetProperty("divergences").EnumerateArray()
            .Select(e => new Divergence(
                e.GetProperty("key").GetString()!,
                e.GetProperty("tool").GetString()!,
                e.GetProperty("reason").GetString()!,
                e.GetProperty("exampleCase").GetString()!))
            .ToList()
            .ToLookup(d => d.Key);
    }

    /// <summary>
    /// Where a language's group directories go. C# and the shared core keys stay at the top of
    /// docs/reference, where every page has always been, so no existing URL moves; each other language
    /// gets a directory of its own beneath it.
    /// </summary>
    private static string LanguageRoot(string outputRoot, OptionLanguage language) => language switch
    {
        OptionLanguage.Shared or OptionLanguage.CSharp => outputRoot,
        OptionLanguage.Xml => Path.Combine(outputRoot, "xml"),
        OptionLanguage.Razor => Path.Combine(outputRoot, "razor"),
        OptionLanguage.FSharp => Path.Combine(outputRoot, "fsharp"),
        _ => throw new ArgumentOutOfRangeException(nameof(language), language, null),
    };

    internal static int Main(string[] args)
    {
        var root = RepoRoot();
        var outputRoot = Path.Combine(root, "docs", "reference");

        Console.WriteLine($"repo root: {root}");
        Console.WriteLine($"output:    {outputRoot}");

        var formatter = new CSharpFormatter();
        using var xmlFormatter = new XmlFormatter();
        var divergences = LoadDivergences(root);
        var unchangedPages = new List<string>();

        var grouped = OptionDescriptor.All
            .GroupBy(d => d.Group)
            .ToDictionary(g => g.Key, g => g.ToList());

        // Write every option page.
        int generated = 0;
        foreach (var descriptor in OptionDescriptor.All)
        {
            var dir = Path.Combine(LanguageRoot(outputRoot, descriptor.Language), GroupDirectory(descriptor.Group));
            Directory.CreateDirectory(dir);

            var snippets = descriptor.Language switch
            {
                OptionLanguage.Xml => Snippets.Xml,
                OptionLanguage.Razor => Snippets.Razor,
                _ => Snippets.All,
            };
            var snippet = snippets.TryGetValue(descriptor.SnippetKey, out var s)
                ? s
                : throw new InvalidOperationException($"Missing snippet '{descriptor.SnippetKey}' for key '{descriptor.Key}'");

            var page = descriptor.Language switch
            {
                OptionLanguage.Xml => BuildXmlPage(descriptor, snippet, xmlFormatter),
                OptionLanguage.Razor => BuildRazorPage(descriptor, snippet),
                _ => BuildPage(descriptor, snippet, formatter, divergences[descriptor.Key], unchangedPages),
            };
            var path = Path.Combine(dir, descriptor.Key + ".md");
            File.WriteAllText(path, page, Encoding.UTF8);
            Console.WriteLine($"  {Path.GetRelativePath(root, path)}");
            generated++;
        }

        // An example whose Before and After match says the key does nothing. A key a code block can't
        // show says so in Snippets.Unshown instead; every other page has to show its key doing something.
        if (unchangedPages.Count > 0)
            throw new InvalidOperationException(
                "No example on these pages shows a change. Give the snippet something the key acts on, give the key the " +
                "settings it needs in Snippets.Companions, or say what it does in Snippets.Unshown:" + Environment.NewLine +
                string.Join(Environment.NewLine, unchangedPages.Select(k => "  " + k)));

        // Write group index pages.
        foreach (var (group, descriptors) in grouped)
        {
            // The reference listing only picks up a group index directly under docs/reference, so a
            // language in a directory of its own is listed through its pages' front matter alone.
            if (descriptors[0].Language is not (OptionLanguage.Shared or OptionLanguage.CSharp))
                continue;

            var title = GroupTitles[group];
            var dir = Path.Combine(LanguageRoot(outputRoot, descriptors[0].Language), GroupDirectory(group));
            Directory.CreateDirectory(dir);

            var sb = new StringBuilder();
            sb.AppendLine(GroupedHeader);
            sb.AppendLine();
            sb.AppendLine($"# {title}");
            sb.AppendLine();
            sb.AppendLine(GroupDescriptions[group]);

            var path = Path.Combine(dir, "index.md");
            File.WriteAllText(path, sb.ToString(), Encoding.UTF8);
            Console.WriteLine($"  {Path.GetRelativePath(root, path)}");
        }

        // Write the top-level options index.
        {
            Directory.CreateDirectory(outputRoot);
            var sb = new StringBuilder();
            sb.AppendLine(GroupedHeader);
            sb.AppendLine();
            sb.AppendLine("# Option Reference");
            sb.AppendLine();
            sb.AppendLine($"Curb implements {OptionDescriptor.All.Count} `.editorconfig` keys. Every key has a before/after example generated by running Curb.");
            sb.AppendLine();
            sb.AppendLine("Use the filter above to search by name. Each group below links to its own index.");
            sb.AppendLine();
            foreach (var (group, descriptors) in grouped)
            {
                var link = Path.GetRelativePath(outputRoot, Path.Combine(LanguageRoot(outputRoot, descriptors[0].Language), GroupDirectory(group))).Replace('\\', '/');
                var title = GroupTitles[group];
                var hasIndex = descriptors[0].Language is OptionLanguage.Shared or OptionLanguage.CSharp;
                sb.AppendLine(hasIndex ? $"## [{title}]({link}/index.md)" : $"## {title}");
                if (!hasIndex)
                {
                    sb.AppendLine();
                    sb.AppendLine(GroupDescriptions[group]);
                }
                sb.AppendLine();
                foreach (var d in descriptors)
                    sb.AppendLine($"- [{d.Key}]({link}/{d.Key}.md) — {d.Summary}");
                sb.AppendLine();
            }
            var path = Path.Combine(outputRoot, "index.md");
            File.WriteAllText(path, sb.ToString(), Encoding.UTF8);
            Console.WriteLine($"  {Path.GetRelativePath(root, path)}");
        }

        Console.WriteLine($"\nDone. {generated} option pages written.");
        return 0;
    }

    private static string BuildPage(
        OptionDescriptor descriptor,
        string snippet,
        CSharpFormatter formatter,
        IEnumerable<Divergence> divergences,
        List<string> unchangedPages)
    {
        var slug = GroupSlugs[descriptor.Group];
        var sb = new StringBuilder();
        sb.AppendLine("---");
        sb.AppendLine($"listing: {slug}");
        sb.AppendLine($"description: \"{descriptor.Summary} Defaults to `{descriptor.Default}`\"");
        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine(GroupedHeader);
        sb.AppendLine();
        sb.AppendLine($"# `{descriptor.Key}`");
        sb.AppendLine();
        sb.AppendLine(descriptor.Summary);
        sb.AppendLine();

        // Values table.
        sb.AppendLine("## Values");
        sb.AppendLine();
        sb.AppendLine("| Value | Notes |");
        sb.AppendLine("|---|---|");
        foreach (var v in descriptor.Values)
        {
            var note = v.StartsWith('<') && v.EndsWith('>') ? "Any integer."
                : Snippets.ValueNotes.TryGetValue((descriptor.Key, v), out var valueNote) ? valueNote
                : "";
            sb.AppendLine($"| `{v}` | {note} |");
        }
        sb.AppendLine();
        sb.AppendLine($"**Default:** `{descriptor.Default}`");
        sb.AppendLine();

        // Conformance: what build/conformance-divergences.json says about this key, or the default
        // claim when it says nothing. See docs/design-principles/conformance.md for what "fixed point"
        // means and why a shape merely differing from a tool's own choice is not itself a divergence.
        sb.AppendLine("## Conformance");
        sb.AppendLine();
        var entries = divergences.ToList();
        if (entries.Count == 0)
        {
            sb.AppendLine(
                "No known case where Curb's output is not a fixed point of `dotnet format` — see " +
                "[conformance](../../design-principles/conformance.md).");
        }
        else
        {
            sb.AppendLine(
                "Curb's output is not always a fixed point of the tool(s) below for this key — see " +
                "[conformance divergences](../../design-principles/conformance-divergences.md) for the full registry.");
            sb.AppendLine();
            foreach (var d in entries)
            {
                sb.AppendLine($"- **{d.Tool}**: {d.Reason} (`{d.ExampleCase}`)");
            }
        }
        sb.AppendLine();

        // A key whose effect a code block can't show says what it does instead of showing two
        // identical blocks.
        if (Snippets.Unshown.TryGetValue(descriptor.Key, out var unshown))
        {
            sb.AppendLine("## Effect");
            sb.AppendLine();
            sb.AppendLine(unshown);
            sb.AppendLine();
            return sb.ToString();
        }

        // Collect the iterable values (skip placeholder shapes like <integer>).
        var iterableValues = descriptor.Values
            .Where(v => !v.StartsWith('<') || !v.EndsWith('>'))
            .ToList();

        // Per-value Before/After sections — no overall "Example" header.
        var input = Snippets.BadSnippets.TryGetValue(descriptor.Key, out var bad) ? bad : snippet;

        // Every example is formatted with the options the CLI binds from the lines it prints: the
        // settings the key needs to act, then the key itself. Before is the same settings without the key.
        var companions = Snippets.Companions.TryGetValue(descriptor.Key, out var c) ? c : [];
        var defaultOutput = Format(formatter, input, Bind(descriptor.Key, companions));
        var startsFromInput = Snippets.StartFromInput.Contains(descriptor.Key);
        var showsAChange = false;

        // A concrete demo value stands in for a freeform placeholder like <template>, which is
        // filtered out of iterableValues below since there is nothing to iterate. Emitted first, so
        // the freeform shape is shown before whatever named values the option also accepts.
        if (Snippets.DemoValues.TryGetValue(descriptor.Key, out var forceVal))
        {
            var lines = companions.Append($"{descriptor.Key} = {forceVal}").ToList();
            var output = Format(formatter, input, Bind(descriptor.Key, lines));
            showsAChange |= Differs(input, output);
            EmitValueSection(sb, descriptor.Key, forceVal, input, output, lines);
        }

        if (iterableValues.Count == 0)
        {
            if (!Snippets.DemoValues.ContainsKey(descriptor.Key))
            {
                sb.AppendLine("*This option accepts a freeform value. No canned example is generated.*");
                sb.AppendLine();
                sb.AppendLine("```ini");
                sb.AppendLine($"{descriptor.Key} = <value>");
                sb.AppendLine("```");
                return sb.ToString();
            }
        }
        else
        {
            foreach (var value in iterableValues)
            {
                var lines = companions.Append($"{descriptor.Key} = {value}").ToList();
                var options = Bind(descriptor.Key, lines);
                var output = Format(formatter, input, options);
                // Default value: Before = raw input. Non-default: Before = default-formatted output, unless
                // the value applied to that output is not After. That is a value which keeps what the author
                // wrote, and the default's output has already been normalised: shown against it, the value
                // would look as though it undid the default. Such a value starts from the input instead.
                var before = value == descriptor.Default || startsFromInput ? input : defaultOutput;
                if (!ReferenceEquals(before, input) && Differs(Format(formatter, before, options), output))
                    before = input;
                showsAChange |= Differs(before, output);
                EmitValueSection(sb, descriptor.Key, value, before, output, lines);
            }
        }

        if (!showsAChange)
            unchangedPages.Add(descriptor.Key);

        return sb.ToString();
    }

    /// <summary>
    /// An XML key's page. XML has no reference formatter, so there is no conformance section; the
    /// examples are Curb's own output for a project file under each value.
    /// </summary>
    private static string BuildXmlPage(OptionDescriptor descriptor, string snippet, XmlFormatter formatter)
    {
        var sb = new StringBuilder();
        sb.AppendLine("---");
        sb.AppendLine($"listing: {GroupSlugs[descriptor.Group]}");
        sb.AppendLine($"description: \"{descriptor.Summary} Defaults to `{descriptor.Default}`\"");
        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine(GroupedHeader);
        sb.AppendLine();
        sb.AppendLine($"# `{descriptor.Key}`");
        sb.AppendLine();
        sb.AppendLine(descriptor.Summary);
        sb.AppendLine();
        sb.AppendLine("## Values");
        sb.AppendLine();
        sb.AppendLine("| Value | Notes |");
        sb.AppendLine("|---|---|");
        foreach (var v in descriptor.Values)
            sb.AppendLine($"| `{v}` | {(v == "<integer>" ? "Any integer." : v == "<extensions>" ? "Comma-separated extensions." : "")} |");
        sb.AppendLine();
        sb.AppendLine($"**Default:** `{descriptor.Default}`");
        sb.AppendLine();
        if (Snippets.XmlNotes.TryGetValue(descriptor.Key, out var note))
        {
            sb.AppendLine(note);
            sb.AppendLine();
        }

        var values = descriptor.Values.Where(v => !v.StartsWith('<')).ToList();
        if (Snippets.DemoValues.TryGetValue(descriptor.Key, out var demo))
            values.Insert(0, demo);

        if (values.Count == 0)
        {
            sb.AppendLine("*This option accepts a freeform value. No canned example is generated.*");
            sb.AppendLine();
            sb.AppendLine("```ini");
            sb.AppendLine($"{descriptor.Key} = <value>");
            sb.AppendLine("```");
            return sb.ToString();
        }

        foreach (var value in values)
        {
            var options = BuildXmlOptions(descriptor.Key, value);
            var after = snippet;
            if (options.Enabled)
            {
                var result = formatter.Format(snippet, options);
                if (!result.Success)
                    throw new InvalidOperationException($"the {descriptor.Key} = {value} example does not format: {result.Message}");
                after = result.Text!;
            }

            EmitValueSection(sb, descriptor.Key, value, snippet, after, language: "xml");
        }

        return sb.ToString();
    }

    /// <summary>
    /// A Razor key's page: what the key does, where it has to go, and a component before and after. Like
    /// XML there is no reference formatter, so no conformance section.
    /// </summary>
    private static string BuildRazorPage(OptionDescriptor descriptor, string snippet)
    {
        var sb = new StringBuilder();
        sb.AppendLine("---");
        sb.AppendLine($"listing: {GroupSlugs[descriptor.Group]}");
        sb.AppendLine($"description: \"{descriptor.Summary} Defaults to `{descriptor.Default}`\"");
        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine(GroupedHeader);
        sb.AppendLine();
        sb.AppendLine($"# `{descriptor.Key}`");
        sb.AppendLine();
        sb.AppendLine(descriptor.Summary);
        sb.AppendLine();
        sb.AppendLine("## Values");
        sb.AppendLine();
        sb.AppendLine("| Value | Notes |");
        sb.AppendLine("|---|---|");
        foreach (var v in descriptor.Values)
            sb.AppendLine($"| `{v}` | |");
        sb.AppendLine();
        sb.AppendLine($"**Default:** `{descriptor.Default}`");
        sb.AppendLine();
        if (Snippets.RazorNotes.TryGetValue(descriptor.Key, out var note))
        {
            sb.AppendLine(note);
            sb.AppendLine();
        }

        // The markup keys are shown at indent_size = 2, where engine quirks indent by tab_width (4) instead.
        var markup = descriptor.Key switch
        {
            RazorFormatter.MarkupKey or RazorFormatter.AttributeIndentKey => RazorMarkup.Indent,
            RazorFormatter.EngineQuirksKey => RazorMarkup.EngineQuirks,
            _ => RazorMarkup.Off,
        };
        var options = markup == RazorMarkup.Off
            ? new FormatOptions { EndOfLine = EndOfLine.Lf }
            : new FormatOptions { EndOfLine = EndOfLine.Lf, IndentSize = 2 };

        using var razor = new RazorFormatter();
        foreach (var value in descriptor.Values)
        {
            var after = snippet;
            if (descriptor.Key == RazorFormatter.AttributeIndentKey || value == "true")
            {
                var attributes = value switch
                {
                    "indent_by_one" => RazorAttributeIndent.IndentByOne,
                    "indent_by_two" => RazorAttributeIndent.IndentByTwo,
                    _ => RazorAttributeIndent.AlignWithFirst,
                };
                var result = razor.Format(snippet, options, markup: markup, attributes: attributes);
                if (!result.Success || result.Declined > 0)
                    throw new InvalidOperationException($"the {descriptor.Key} = {value} example does not format: {result.Message}");
                after = result.Text!;
            }

            EmitValueSection(sb, descriptor.Key, value, snippet, after, language: "html");
        }

        return sb.ToString();
    }

    private static XmlOptions BuildXmlOptions(string key, string value)
    {
        var options = new XmlOptions { Profile = XmlProfile.MsBuild, Layout = XmlOptions.DefaultLayout with { EndOfLine = EndOfLine.Lf } };
        return key switch
        {
            "curb_xml_format" => options with { Enabled = value == "true" },
            "xml_max_blank_lines_between_tags" => options with { MaxBlankLines = int.Parse(value, System.Globalization.CultureInfo.InvariantCulture) },
            "xml_space_before_self_closing" => options with { SpaceBeforeSelfClosingOption = value == "true" ? SelfClosingSpace.Always : SelfClosingSpace.Never },
            "xml_attribute_indent" => options with
            {
                AttributeIndent = value switch
                {
                    "single_indent" => AttributeIndent.SingleIndent,
                    "double_indent" => AttributeIndent.DoubleIndent,
                    _ => AttributeIndent.AlignByFirstAttribute,
                },
            },
            _ => options,
        };
    }

    private static void EmitValueSection(
        StringBuilder sb, string key, string value, string before, string after, IReadOnlyList<string>? ini = null, string language = "csharp")
    {
        sb.AppendLine($"### `{key} = {value}`");
        sb.AppendLine();
        sb.AppendLine("```ini");
        foreach (var line in ini ?? [$"{key} = {value}"])
            sb.AppendLine(line);
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("::::{tab-set}");
        sb.AppendLine();
        sb.AppendLine(":::{tab-item} Before");
        sb.AppendLine($"```{language}");
        sb.Append(before.TrimEnd());
        sb.AppendLine();
        sb.AppendLine("```");
        sb.AppendLine(":::");
        sb.AppendLine();
        sb.AppendLine(":::{tab-item} After");
        sb.AppendLine($"```{language}");
        sb.Append(after.TrimEnd());
        sb.AppendLine();
        sb.AppendLine("```");
        sb.AppendLine(":::");
        sb.AppendLine();
        sb.AppendLine("::::");
        sb.AppendLine();
    }

    /// <summary>
    /// The options <c>curb format</c> resolves from <paramref name="lines"/>, bound by the CLI's own
    /// binder. A diagnostic fails the run: it means the CLI would ignore or reject a setting the page
    /// prints, so the example would show output nobody can get.
    /// </summary>
    private static FormatOptions Bind(string key, IReadOnlyList<string> lines)
    {
        var diagnostics = new List<CurbDiagnostic>();
        var options = EditorConfigText.Bind(lines, diagnostics);
        if (diagnostics.Count > 0)
            throw new InvalidOperationException(
                $"The {key} example's settings do not bind cleanly, so curb format would not do what the page shows:" + Environment.NewLine +
                string.Join(Environment.NewLine, lines.Select(l => "  " + l)) + Environment.NewLine +
                string.Join(Environment.NewLine, diagnostics.Select(d => $"  {d.Id}: {d.Message}")));
        return options;
    }

    private static string Format(CSharpFormatter formatter, string input, FormatOptions options)
    {
        // The CLI skips an excluded file before it reaches the formatter (generated_code, an IDE0055
        // severity of none), so the formatter itself doesn't look at the flag.
        if (options.Excluded)
            return input;

        var result = formatter.Format(input, options, produceText: true);
        return result.Success ? (result.Text ?? input) : input;
    }

    /// <summary>Whether two examples render differently, which is what a reader of the page can see.</summary>
    private static bool Differs(string before, string after) => before.TrimEnd() != after.TrimEnd();
