module CommandLine

open Nullean.Make.Fs

/// The build's targets; `./build.sh --help` lists them with these descriptions.
///
/// Make.Fs names a target after its case, kebab-cased at each capital, so the multi-word names CI, mise.toml
/// and the docs call (`clonecorpus`, `verifyexpectationside0055`, ...) are spelled here with one capital.
type Target =
    /// clean known output locations
    | Clean
    /// runs build
    | Build
    /// runs build then tests
    | Test
    /// runs the BenchmarkDotNet suite against the AOT-published binary
    | Benchmark
    /// measures agreement with dotnet format over a corpus (--corpus <path>)
    | Conformance
    /// measures how many of a corpus's files Curb rewrites (--corpus <path>)
    | Churn
    /// times the AOT binary over a corpus (--corpus <path>); never measure the JIT build
    | Perf
    /// times curb, csharpier and dotnet format over a directory of repos (--corpus <dir>)
    | Compare
    /// generates docs/reference/**/*.md by running Curb against each option's snippet
    | Options
    /// builds the public docs, applies the landing page override, and serves them
    | Docs
    /// writes the corpus the corpus gates run against into --corpus <path>, generated by default; the one place CI gets it from
    | Clonecorpus
    /// prove the MSBuild integration runs before the compiler
    | Msbuildsmoketest
    /// prove the MSBuild integration formats an F# project through its pinned Fantomas, and skips when nothing changed
    | Fsharpsmoketest
    /// prove curb cleanup fixes what a build reported, and only that
    | Cleanupsmoketest
    /// feed a corpus wrong verdicts and prove none of them damages a file (--corpus <path>)
    | Cleanupsafety
    /// clean a corpus that builds, and prove it still builds and dotnet format style agrees
    | Cleanupconformance
    /// format a corpus's project files and prove MSBuild evaluates every project the same before and after (--corpus <path>)
    | Xmlsafety
    /// prove every expectation in the test suite survives dotnet format
    | Verifyexpectations
    /// prove every cleanup-rule case in the test suite is a fixed point of dotnet format style
    | Verifycleanupexpectations
    /// measures how many expectations in the test suite are a fixed point of jb cleanupcode; reported only, not gated (jb's own processing is not deterministic at this batch size yet)
    | Verifyexpectationsjb
    /// prove every expectation in the test suite reports no IDE0055 under a real, analyzer-driven dotnet build — a fixed point of dotnet format whitespace is not the same claim
    | Verifyexpectationside0055
    /// prove every Razor expectation in the test suite is a fixed point of Microsoft's Razor formatter, the engine dotnet format is getting for Razor, or a documented divergence
    | Verifyrazorexpectations
    /// packs the MSBuild package and the CLI's root and portable tool packages into build/output (the per-RID AOT packages come from CI's matrix)
    | Generatepackages
    /// validates the signed assemblies in build/output's packages against the informational version
    | Validatepackages
    /// writes the public API changes since the previous release of every managed package in build/output
    | Generateapichanges
    /// publishes the CLI's native-AOT build as a container image (--push to push it to ghcr.io)
    | Publishcontainers

let app = MakeApp<Target>("./build.sh", None)

// The spellings are the ones the Argu build accepted (Argu dropped the case's capitals rather than hyphenating
// them), because those are what CI passes: `--maxallocationratio`, `--corpussource`, `--corpussize`, `--noserve`.
// `-s` (`--single-target`) belongs to Make.Fs itself; it is a flag now, and the `-s true` CI and mise.toml pass
// still works, since a target without a typed payload ignores the `true` left over.

let corpus = app.Option<string option>("--corpus", desc = "path to a checkout (or a directory of checkouts for compare)", defaultValue = None)
let minimum = app.Option<float option>("--minimum", desc = "fail if conformance falls below this percentage", defaultValue = None)
let maxAllocationRatio =
    app.Option<float option>("--maxallocationratio", desc = "fail if perf allocates more than this multiple of the source size", defaultValue = None)
let trailingCommas = app.Flag("--trailingcommas", desc = "measure conformance with ReSharper's trailing-comma keys on")
let reflow = app.Flag("--reflow", desc = "keep the corpus's own max_line_length instead of forcing it off")
let port = app.Option<int>("--port", desc = "port to serve the documentation on (default 8080)", defaultValue = 8080)
let noServe = app.Flag("--noserve", desc = "build the documentation without serving it")
let deterministic =
    app.Flag("--deterministic", desc = "force csharp_keep_existing_linebreaks = false; implies --reflow. Redundant now that a width selects it")
let preserve = app.Flag("--preserve", desc = "force csharp_keep_existing_linebreaks = true, the opt-out a width no longer gives you")
let width = app.Option<int option>("--width", desc = "override the corpus's max_line_length with this column count", defaultValue = None)
let maximum = app.Option<float option>("--maximum", desc = "fail if churn rises above this percentage of files", defaultValue = None)
let shard =
    app.Option<string option>(
        "--shard",
        desc = "verifyexpectationside0055 only: check shard i of n (e.g. 1/4); a case's shard is a stable hash of its test name, so the n shards together cover every case exactly once",
        defaultValue = None)
let corpusSource =
    app.Option<string option>(
        "--corpussource",
        desc = "clonecorpus/cleanupconformance: generated (default; tools/Nullean.Curb.CorpusGenerator) or docs-builder (a clone of elastic/docs-builder at HEAD, for comparison)",
        defaultValue = None)
let seed =
    app.Option<int option>(
        "--seed", desc = "clonecorpus: the generator's seed (default 1); the same seed and test suite give a byte-identical corpus", defaultValue = None)
let corpusSize =
    app.Option<float option>(
        "--corpussize", desc = "clonecorpus: megabytes of generated C# on top of the test suite's snippets (default 10)", defaultValue = None)
let push =
    app.Flag("--push", desc = "publishcontainers only: push the built image to ghcr.io instead of building it into the local Docker daemon")
